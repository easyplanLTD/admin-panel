// supabase/functions/generate-test-data/index.ts
//
// Creates system-generated "Test Jobs" and "Test SP's", per the settings
// on the `test_generators` table (edited from Settings -> System -> Test
// in FixFlow -- see TestGeneratorsPanel in src/App.jsx).
//
// Two ways this runs:
//
// 1. On a schedule, via pg_cron -> pg_net (see the bottom of
// 0005_test_generators.sql), roughly every 15 minutes. There's no
// logged-in user on this path, so it authenticates instead with a
// shared secret in the `x-cron-secret` header, checked against the
// CRON_SECRET env var. On this path each generator only actually
// fires if it's `enabled`, its interval has elapsed since
// `last_run_at`, AND a random roll against `volume` passes -- see the
// comment on that column in the migration for why "volume" is a
// probability rather than a raw count.
//
// 2. On demand, from the "Generate one batch now" button on that same
// settings page -- an owner/staff session calling this with
// { force: true, only: "jobs" | "sps" }. This ignores `enabled`,
// the interval, and the volume roll, and just creates `amount_per_run`
// rows for that one generator right now, so someone can see what it
// does without waiting for (or turning on) the schedule.
//
// Safety note on Test SP's: they're created inactive (`active: false`)
// with no postcodes/appliance types, specifically so the real auto-assign
// logic never hands a genuine customer's booking to a fake engineer. Test
// Jobs are inserted unassigned for the same reason -- they exist to
// exercise the dashboard/notifications/list UI, not to dispatch real work.
//
// Deploy with: supabase functions deploy generate-test-data
// Then set the cron secret once: supabase secrets set CRON_SECRET=<same value as the vault secret in 0005>

import { createClient } from "npm:@supabase/supabase-js@2";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL");
const SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
const CRON_SECRET = Deno.env.get("CRON_SECRET");

const corsHeaders = {
"Access-Control-Allow-Origin": "*",
"Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-cron-secret",
"Access-Control-Allow-Methods": "POST, OPTIONS",
};

function json(body, status = 200) {
return new Response(JSON.stringify(body), {
status,
headers: { "Content-Type": "application/json", ...corsHeaders },
});
}

const INTERVAL_MS = {
"15m": 15 * 60 * 1000,
"30m": 30 * 60 * 1000,
"45m": 45 * 60 * 1000,
"1h": 60 * 60 * 1000,
"2h": 2 * 60 * 60 * 1000,
"3h": 3 * 60 * 60 * 1000,
"1d": 24 * 60 * 60 * 1000,
};

const FIRST_NAMES = ["Alex","Sam","Jordan","Taylor","Casey","Morgan","Riley","Jamie","Charlie","Drew","Robin","Frankie"];
const LAST_NAMES = ["Test","Sample","Example","Demo","Placeholder","Fixture","Trial","Mock"];
const APPLIANCE_TYPES = ["Washing Machine","Tumble Dryer","Dishwasher","Fridge/Freezer","Oven/Cooker","Hob","Microwave"];
const BRANDS = ["Bosch","Samsung","LG","Hotpoint","Beko","AEG","Indesit","Siemens"];
const ISSUES = [
"Not turning on", "Making a loud noise", "Leaking water", "Not heating",
"Door won't close properly", "Stopped mid-cycle", "Tripping the electrics", "Display showing an error code",
];
const POSTCODE_PREFIXES = ["M","B","LS","S","L","BS","NE","G","EH","CF"];
const STATUS_WEIGHTS = ["Quote","Booked","Booked","Booked"];

function pick(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
function randDigits(n) { let s = ""; for (let i = 0; i < n; i++) s += Math.floor(Math.random() * 10); return s; }
function fakePostcode() { return `${pick(POSTCODE_PREFIXES)}${Math.floor(Math.random()*20)+1} ${Math.floor(Math.random()*10)}${"ABCDEFGHJKLMNPQRSTUVWXYZ"[Math.floor(Math.random()*24)]}${"ABCDEFGHJKLMNPQRSTUVWXYZ"[Math.floor(Math.random()*24)]}`; }
function uniqueSuffix() { return `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`; }
function generateTempPassword() {
const chars = "ABCDEFGHJKMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789";
let out = "";
for (let i = 0; i < 12; i++) out += chars[Math.floor(Math.random() * chars.length)];
return out;
}

async function generateTestJobs(admin, count) {
const rows = Array.from({ length: count }).map(() => ({
customer: `${pick(FIRST_NAMES)} ${pick(LAST_NAMES)}`,
phone: `07700900${randDigits(3)}`,
email: `test-${uniqueSuffix()}@test.easyrepair.internal`,
address: "Generated by Settings -> System -> Test",
postcode: fakePostcode(),
appliance: pick(APPLIANCE_TYPES),
brand: pick(BRANDS),
issue: pick(ISSUES),
source: "Test",
status: pick(STATUS_WEIGHTS),
priority: "Normal",
is_test: true,
}));
const { data, error } = await admin.from("bookings").insert(rows).select("id");
if (error) throw new Error(error.message);
return data.length;
}

async function generateTestSPs(admin, count) {
let created = 0;
for (let i = 0; i < count; i++) {
const name = `${pick(FIRST_NAMES)} ${pick(LAST_NAMES)}`;
const email = `test-sp-${uniqueSuffix()}@test.easyrepair.internal`;
const { data: userData, error: userErr } = await admin.auth.admin.createUser({
email,
password: generateTempPassword(),
email_confirm: true,
user_metadata: { name, role: "engineer", phone: `07700900${randDigits(3)}` },
});
if (userErr || !userData?.user) continue;

const { error: engErr } = await admin.from("engineers").insert({
profile_id: userData.user.id,
pay_rate: 45,
postcodes: [],
appliance_types: [],
brand_exclusions: {},
self_service_enabled: false,
active: false,
});
if (engErr) { await admin.auth.admin.deleteUser(userData.user.id); continue; }

await admin.from("profiles").update({ is_test: true }).eq("id", userData.user.id);
created++;
}
return created;
}

async function runGenerator(admin, row) {
const count = row.type === "jobs" ? await generateTestJobs(admin, row.amount) : await generateTestSPs(admin, row.amount);
return count;
}

Deno.serve(async (req) => {
if (req.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
if (req.method !== "POST") return json({ error: "Method not allowed" }, 405);

const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
auth: { autoRefreshToken: false, persistSession: false },
});

let body = {};
try { body = await req.json(); } catch { /* empty body from cron is fine */ }

const cronSecret = req.headers.get("x-cron-secret") || "";
const isCron = !!CRON_SECRET && cronSecret === CRON_SECRET;

if (!isCron) {
const authHeader = req.headers.get("Authorization") || "";
const callerJwt = authHeader.replace(/^Bearer /i, "");
if (!callerJwt) return json({ error: "Missing Authorization header" }, 401);

const { data: callerData, error: callerErr } = await admin.auth.getUser(callerJwt);
if (callerErr || !callerData?.user) return json({ error: "Invalid session" }, 401);

const { data: callerProfile, error: profileErr } = await admin
.from("profiles").select("role").eq("id", callerData.user.id).single();
if (profileErr || !callerProfile || !["owner", "staff"].includes(callerProfile.role)) {
return json({ error: "Only owner/staff accounts can trigger test data generation" }, 403);
}
if (!body?.force) return json({ error: "Missing x-cron-secret, and this call isn't a forced manual run" }, 401);
}

const { data: generators, error: loadErr } = await admin.from("test_generators").select("*");
if (loadErr) return json({ error: loadErr.message }, 500);

const results = [];

for (const gen of generators || []) {
if (body?.force) {
if (body.only && body.only !== gen.id) continue;
try {
const created = await runGenerator(admin, { type: gen.id, amount: gen.amount_per_run });
await admin.from("test_generators").update({
last_run_at: new Date().toISOString(), last_run_created: created, last_run_status: "ok (manual)",
}).eq("id", gen.id);
results.push({ id: gen.id, created, status: "ok (manual)" });
} catch (e) {
await admin.from("test_generators").update({
last_run_at: new Date().toISOString(), last_run_created: 0, last_run_status: `error: ${e.message}`,
}).eq("id", gen.id);
results.push({ id: gen.id, created: 0, status: `error: ${e.message}` });
}
continue;
}

if (!gen.enabled) continue;
const intervalMs = INTERVAL_MS[gen.interval_key] || INTERVAL_MS["1h"];
const due = !gen.last_run_at || (Date.now() - new Date(gen.last_run_at).getTime()) >= intervalMs;
if (!due) continue;

const firing = Math.random() * 100 < gen.volume;
if (!firing) {
await admin.from("test_generators").update({
last_run_at: new Date().toISOString(), last_run_created: 0, last_run_status: "skipped (volume roll)",
}).eq("id", gen.id);
results.push({ id: gen.id, created: 0, status: "skipped (volume roll)" });
continue;
}

try {
const created = await runGenerator(admin, { type: gen.id, amount: gen.amount_per_run });
await admin.from("test_generators").update({
last_run_at: new Date().toISOString(), last_run_created: created, last_run_status: "ok",
}).eq("id", gen.id);
results.push({ id: gen.id, created, status: "ok" });
} catch (e) {
await admin.from("test_generators").update({
last_run_at: new Date().toISOString(), last_run_created: 0, last_run_status: `error: ${e.message}`,
}).eq("id", gen.id);
results.push({ id: gen.id, created: 0, status: `error: ${e.message}` });
}
}

return json({ results });
});